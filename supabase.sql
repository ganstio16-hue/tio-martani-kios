create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  category text not null default 'Lainnya',
  selling_price numeric(14,2) not null default 0 check (selling_price >= 0),
  cost_price numeric(14,2) check (cost_price is null or cost_price >= 0),
  unit text not null default 'pcs',
  photo_path text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.price_history (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  product_id uuid not null references public.products(id) on delete cascade,
  old_price numeric(14,2) not null,
  new_price numeric(14,2) not null,
  changed_at timestamptz not null default now()
);

create index if not exists products_owner_updated_idx on public.products(owner_id, updated_at desc);
create index if not exists products_owner_category_idx on public.products(owner_id, category);
create index if not exists price_history_product_changed_idx on public.price_history(product_id, changed_at desc);

alter table public.products enable row level security;
alter table public.price_history enable row level security;

drop policy if exists "Owner can read own products" on public.products;
create policy "Owner can read own products" on public.products for select to authenticated using (auth.uid() = owner_id);
drop policy if exists "Owner can add own products" on public.products;
create policy "Owner can add own products" on public.products for insert to authenticated with check (auth.uid() = owner_id);
drop policy if exists "Owner can update own products" on public.products;
create policy "Owner can update own products" on public.products for update to authenticated using (auth.uid() = owner_id) with check (auth.uid() = owner_id);
drop policy if exists "Owner can delete own products" on public.products;
create policy "Owner can delete own products" on public.products for delete to authenticated using (auth.uid() = owner_id);

drop policy if exists "Owner can read own price history" on public.price_history;
create policy "Owner can read own price history" on public.price_history for select to authenticated using (auth.uid() = owner_id);

create or replace function public.log_product_price_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.updated_at := now();
  if old.selling_price is distinct from new.selling_price then
    insert into public.price_history(owner_id, product_id, old_price, new_price)
    values (new.owner_id, new.id, old.selling_price, new.selling_price);
  end if;
  return new;
end;
$$;

drop trigger if exists products_price_change_trigger on public.products;
create trigger products_price_change_trigger
before update on public.products
for each row execute function public.log_product_price_change();

